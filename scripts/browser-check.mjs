import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(path.join(root, '.tools/browser-tools/package.json'));
const { chromium } = require('playwright');
const id = process.argv[2];
if (!/^[0-9a-f-]{36}$/i.test(id || '')) throw new Error('Requiere fixture temporal de Offers.Checks.');
const browser = await chromium.launch({ executablePath: process.env.Capture__BrowserExecutablePath || undefined, headless: true });
const base = process.env.OFFERS_CHECKS_FRONTEND_URL || 'http://127.0.0.1:5175';
let step = 'inicio';
let page;
try {
  page = await browser.newPage();
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  step = 'catálogo'; await page.goto(base);
  await page.getByRole('heading', { name: 'Ofertas en un solo lugar', exact: true }).waitFor();
  fs.mkdirSync(path.join(root, '.tools/screenshots'), { recursive: true });
  await page.screenshot({ path: path.join(root, '.tools/screenshots/catalog.png'), fullPage: true });
  step = 'detalle'; await page.goto(`${base}/?offer=${id}`);
  await page.locator('.code').waitFor();
  assert((await page.locator('.code').textContent()) === 'Test-aB-01', 'Código alterado');
  assert(await page.getByRole('button', { name: /copiar/i }).count() === 0, 'Botón de copiado fuera del MVP');
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Desborde horizontal móvil');
  await page.screenshot({ path: path.join(root, '.tools/screenshots/mobile-detail.png'), fullPage: true });
  step = 'seleccionar motivo'; await page.getByLabel('Motivo', { exact: true }).selectOption('IncorrectData');
  step = 'comentario'; await page.getByLabel('Comentario opcional', { exact: true }).fill('Reporte de prueba desde navegador');
  step = 'enviar reporte'; await page.getByRole('button', { name: 'Enviar reporte', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Reporte enviado' }).waitFor();
  step = 'origen'; const responsePromise = page.waitForResponse(r => r.url().endsWith(`/api/offers/${id}/source-access`) && r.request().method() === 'POST');
  const popupPromise = page.waitForEvent('popup');
  await page.getByRole('link', { name: 'Ver oferta en origen' }).click();
  const response = await responsePromise; assert(response.status() === 204, 'Acceso no registrado');
  const popup = await popupPromise; await popup.close();
  step = 'administración'; await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto(`${base}/?admin=1`);
  await page.getByLabel('Usuario', { exact: true }).fill(process.env.Admin__Username);
  await page.getByLabel('Contraseña', { exact: true }).fill(process.env.Admin__Password);
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  const reports = page.getByRole('region', { name: 'Reportes recibidos' });
  await reports.getByText('Reporte de prueba desde navegador', { exact: true }).waitFor();
  await reports.getByRole('listitem').filter({ hasText: 'Reporte de prueba desde navegador' }).getByRole('button').click();
  const review = page.getByRole('region', { name: 'Revisión de la oferta' });
  await review.waitFor();
  assert(await review.getByRole('button', { name: 'Enviar reporte' }).count() === 0, 'Formulario público en administración');
  step = 'logout'; await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click();
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).waitFor();
  console.log('OK: navegador real verifica catálogo, detalle móvil, reporte, origen, revisión administrativa y logout.');
} catch (error) {
  if (page) await page.screenshot({ path: path.join(root, '.tools/screenshots/failure.png'), fullPage: true }).catch(() => {});
  console.error(`FAIL: navegador en etapa ${step} (${error.name}). Revisar servicios y selectores; no se imprimen credenciales.`);
  process.exitCode = 1;
} finally { await browser.close(); }
